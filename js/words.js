WB.Words = (() => {
  const USED_KEY = "wb.usedWords";
  // نرفع الرقم كل ما تغيّر البنك، عشان سجل الكلمات المستخدمة يبدأ من جديد
  const BANK_VERSION = "3";
  try {
    if (localStorage.getItem("wb.bankVersion") !== BANK_VERSION) {
      localStorage.removeItem(USED_KEY);
      localStorage.setItem("wb.bankVersion", BANK_VERSION);
    }
  } catch { /* تجاهل */ }

  const LEVEL_IDS = Object.keys(WB.LEVELS);
  const byId = new Map();
  WB.CATEGORIES.forEach((c) => {
    LEVEL_IDS.forEach((lv) => {
      (c[lv] || []).forEach((w, i) => {
        const id = `${c.id}:${lv}:${i}`;
        byId.set(id, { id, text: w, cat: c.id, catName: c.name, level: lv, levelName: WB.LEVELS[lv] });
      });
    });
  });

  function loadUsed() {
    try { return new Set(JSON.parse(localStorage.getItem(USED_KEY) || "[]")); } catch { return new Set(); }
  }
  function saveUsed(set) {
    try { localStorage.setItem(USED_KEY, JSON.stringify([...set])); } catch { /* تجاهل */ }
  }

  const rand = (arr) => arr[Math.floor(Math.random() * arr.length)];

  /** توزيع عادل: فئة عشوائية، ثم مستوى عشوائي، ثم كلمة ما طلعت قبل.
      إذا خلصت كلمات مستوى في فئة، نبدأ له دورة جديدة.
      exclude: معرّفات إضافية لا تُختار (مثل الكلمات المستخدمة في الغرفة). */
  function pick(categoryIds, exclude = []) {
    const cats = WB.CATEGORIES.filter((c) => categoryIds.includes(c.id));
    const pool = cats.length ? cats : WB.CATEGORIES;
    const cat = rand(pool);
    const level = rand(LEVEL_IDS.filter((lv) => (cat[lv] || []).length));
    const ids = cat[level].map((_, i) => `${cat.id}:${level}:${i}`);

    const used = loadUsed();
    const ex = new Set(exclude);
    let left = ids.filter((id) => !used.has(id) && !ex.has(id));
    if (!left.length) {
      ids.forEach((id) => used.delete(id));
      saveUsed(used);
      left = ids.filter((id) => !ex.has(id));
      if (!left.length) left = ids;
    }
    return byId.get(rand(left));
  }

  function markUsed(id) {
    if (!byId.has(id)) return;
    const used = loadUsed();
    used.add(id);
    saveUsed(used);
  }

  function reset() { saveUsed(new Set()); }
  function get(id) { return byId.get(id) || null; }
  function count() { return byId.size; }

  return { pick, markUsed, reset, get, count };
})();
